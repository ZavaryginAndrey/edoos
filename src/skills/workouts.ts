import { tool } from "@openai/agents";
import { z } from "zod";

// Шаблоны намеренно общие: под профиль (велосипед, boulder, отсутствие зала) их адаптирует коуч.
// Интенсивность — по ощущениям (RPE 1–10), без пульсовых зон: это не медицинская рекомендация.
const TEMPLATES = {
  fat_loss: `# Шаблон: снижение веса и рельеф
- Частота: 4–5 активностей в неделю + ежедневная бытовая активность.
- Аэробная работа «зона 2» (RPE 4–5, можно говорить фразами): 3 × 30–45 мин — велосипед, быстрая ходьба.
- Силовая круговая с весом тела: 2 × 30 мин. 3 круга без отдыха между упражнениями, 90 с между кругами:
  приседания 15, отжимания 10–15, выпады 10 на ногу, тяга резины к поясу 15, планка 40 с.
- Шаги: +2 000 к текущему среднему, затем до 8 000–10 000 в день.
- Прогрессия: раз в неделю +1 круг или +5 мин аэробной работы, но не всё сразу.`,

  endurance: `# Шаблон: выносливость
- Частота: 3 целевые сессии в неделю.
- Интервалы: 1 × в неделю, разминка 10 мин, затем 4 × 4 мин на RPE 8 через 3 мин лёгкого хода, заминка 5 мин.
- Длинная аэробная: 1 × 45–60 мин на RPE 4–5 (велосипед или бег трусцой).
- Темповая: 1 × 20 мин на RPE 6–7 — например, подъём в горку в одном темпе без рывков.
- Прогрессия: каждые 2 недели +1 интервал или +10 мин к длинной сессии.
- Не ставь интервалы и тяжёлую силовую работу на соседние дни.`,

  strength: `# Шаблон: сила и тонус (без зала)
- Частота: 2–3 full-body тренировки в неделю, между ними минимум день отдыха.
- Упражнения, 3–4 подхода по 6–10 повторений, отдых 90–120 с:
  подтягивания или австралийские подтягивания, отжимания (усложнять наклоном или паузой),
  приседания с гирей или гантелью, румынская тяга на одной ноге, планка 3 × 45 с.
- Если есть лазание (boulder), тянущие упражнения в тот же день сокращай вдвое.
- Прогрессия: +1–2 повторения за неделю; дошёл до 10 — усложни вариант упражнения.`,

  mobility: `# Шаблон: мобильность и восстановление
- Частота: ежедневно 10–15 мин, можно после работы или перед сном.
- Грудной отдел: вращения на четвереньках 2 × 8 на сторону, «кошка-корова» 10 раз.
- Плечи: круги с резиной 2 × 12, вис на перекладине 3 × 20–30 с.
- Таз и бёдра: выпад с растяжкой сгибателя бедра 2 × 40 с на сторону, «голубь» 2 × 40 с.
- Предплечья и запястья: растяжка сгибателей и разгибателей 2 × 30 с.
- Раз в неделю — 30–40 мин лёгкой прогулки или ролла вместо интенсивной нагрузки.`,
} as const;

export const suggestWorkoutTemplate = tool({
  name: "suggestWorkoutTemplate",
  description:
    "Возвращает готовый недельный шаблон тренировок под одну цель: частота, упражнения, подходы и повторения, " +
    "интенсивность по ощущениям (RPE 1–10) и правило прогрессии. Шаблон общий: адаптируй его под профиль " +
    "(график, уже имеющиеся нагрузки, доступный инвентарь), а не копируй целиком. " +
    "Вызывай, когда задача касается тренировок, активности, выносливости или формы; для чисто пищевых запросов не нужен. " +
    "Под несколько целей вызывай несколько раз.",
  parameters: z.object({
    goal: z
      .enum(["fat_loss", "endurance", "strength", "mobility"])
      .describe(
        "Цель шаблона: fat_loss — снижение веса и рельеф; endurance — выносливость (кардио, подъёмы); " +
        "strength — сила и тонус без зала; mobility — мобильность и восстановление.",
      ),
  }),
  execute: ({ goal }) => TEMPLATES[goal],
});
